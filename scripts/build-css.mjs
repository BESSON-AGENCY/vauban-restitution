// Builds src/css.generated.ts (the documentary CSS of the design system, pruned to the classes the
// compositions use, minified) and src/css.restitution.ts (the restitution profile, ours).
// The DS copies in src/css/ stay verbatim: scripts/check-ds-drift.mjs compares them to the DS repository.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const DS_FILES = ['tokens-print.css', 'components.css', 'editorial.css', 'pages.css', 'decisions.css'];

// Classes the compositions emit: every vd-/va-/vr- token written in src/compose.
const used = new Set();
for (const f of readdirSync(join(root, 'src/compose'))) {
  const text = readFileSync(join(root, 'src/compose', f), 'utf8');
  for (const m of text.matchAll(/\b(?:vd|va|vr)-[a-z0-9-]+/g)) used.add(m[0]);
}

const classesOf = (selector) => [...selector.matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)].map((m) => m[1]);
const keeps = (selector) => classesOf(selector).every((c) => used.has(c));

function prune(css) {
  const ast = postcss.parse(css);
  ast.walkAtRules('import', (n) => n.remove());
  ast.walkRules((rule) => {
    if (rule.parent?.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
    const kept = rule.selectors.filter(keeps);
    if (kept.length === 0) rule.remove();
    else rule.selectors = kept;
  });
  ast.walkAtRules((at) => {
    if (/keyframes$/.test(at.name) || at.name === 'font-face') at.remove();
  });
  // Empty at-rules, deepest first.
  for (let pass = 0; pass < 3; pass++) {
    ast.walkAtRules((at) => {
      if (at.nodes && at.nodes.length === 0 && !['page'].includes(at.name)) at.remove();
    });
  }
  return ast;
}

const clean = (s) => s.replace(/\s+/g, ' ').trim();

function emit(node) {
  switch (node.type) {
    case 'root':
      return node.nodes.map(emit).join('');
    case 'rule':
      return `${clean(node.selectors.join(','))}{${node.nodes.map(emit).join(';')}}`;
    case 'atrule': {
      const params = clean(node.params).replace(/\s*:\s*/g, ':');
      const head = `@${node.name}${params ? ' ' + params : ''}`;
      return node.nodes ? `${head}{${node.nodes.map(emit).join(node.nodes[0]?.type === 'decl' ? ';' : '')}}` : `${head};`;
    }
    case 'decl':
      return `${node.prop}:${clean(node.value)}${node.important ? '!important' : ''}`;
    default:
      return '';
  }
}

function minify(css, doPrune) {
  const ast = doPrune ? prune(css) : postcss.parse(css);
  ast.walkComments((c) => c.remove());
  return emit(ast);
}

const ds = DS_FILES.map((f) => minify(readFileSync(join(root, 'src/css', f), 'utf8'), true)).join('');

// The restitution profile (ours): every rule scoped under .vr-restitution so that it wins over the DS rules.
function scoped(css) {
  const ast = postcss.parse(css);
  ast.walkRules((rule) => {
    if (rule.parent?.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
    rule.selectors = rule.selectors.map((s) => (/^(body|:root|html)\b/.test(s) ? s : `.vr-restitution ${s}`));
  });
  return ast;
}
const profileAst = scoped(readFileSync(join(root, 'src/css/profile.css'), 'utf8'));
profileAst.walkComments((c) => c.remove());
const own = emit(profileAst);

const header = '// Generated by scripts/build-css.mjs. Do not edit.\n';
writeFileSync(join(root, 'src/css.generated.ts'), `${header}export const DS_CSS: string = ${JSON.stringify(ds)};\n`);
writeFileSync(join(root, 'src/css.restitution.ts'), `${header}export const RESTITUTION_CSS: string = ${JSON.stringify(own)};\n`);
console.log(`css: ds ${ds.length} bytes, own ${own.length} bytes, ${used.size} classes used`);
